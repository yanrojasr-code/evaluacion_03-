-- Catálogo de tipos
CREATE TABLE tipo_vivienda (
    id_tipo      NUMBER(2)     NOT NULL,
    descripcion  VARCHAR2(30)  NOT NULL,
    CONSTRAINT pk_tipo_vivienda PRIMARY KEY (id_tipo),
    CONSTRAINT uq_tipo_vivienda_descripcion UNIQUE (descripcion)
);

-- Registros.
-- piso, gasto_comun_al_dia, estacionamiento se usan solo para Departamento;
-- patio se usa solo para Casa.
-- Los valores lógicos se guardan como 1 (sí) o 0 (no).
CREATE TABLE vivienda (
    id                    NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_tipo               NUMBER(2)     NOT NULL,
    codigo                VARCHAR2(80)  NOT NULL,
    superficie            NUMBER(10,2)  NOT NULL,
    habitaciones          NUMBER(10)    NOT NULL,
    piso                  NUMBER(10),
    gasto_comun_al_dia    NUMBER(1),
    estacionamiento       NUMBER(1),
    patio                 NUMBER(1),
    CONSTRAINT pk_vivienda PRIMARY KEY (id),
    CONSTRAINT fk_vivienda_tipo FOREIGN KEY (id_tipo) REFERENCES tipo_vivienda (id_tipo),
    CONSTRAINT ck_vivienda_superficie CHECK (superficie BETWEEN 20 AND 500),
    CONSTRAINT ck_vivienda_habitaciones CHECK (habitaciones > 0),
    CONSTRAINT ck_vivienda_piso CHECK (piso > 0),
    CONSTRAINT ck_vivienda_gasto_comun_al_dia CHECK (gasto_comun_al_dia IN (0, 1)),
    CONSTRAINT ck_vivienda_estacionamiento CHECK (estacionamiento IN (0, 1)),
    CONSTRAINT ck_vivienda_patio CHECK (patio IN (0, 1))
);

